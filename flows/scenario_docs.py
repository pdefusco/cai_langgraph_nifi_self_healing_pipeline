def cell(text) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def code(text) -> str:
    text = cell(text)

    return f"`{text}`" if "`" not in text else text


def plural(n: int, noun: str) -> str:
    return f"{n} {noun}" if n == 1 else f"{n} {noun}s"


def number(value) -> str:
    return f"{value:,g}"


def join(items, word: str = "and") -> str:
    items = list(items)

    return items[0] if len(items) == 1 else f"{', '.join(items[:-1])} {word} {items[-1]}"


def words(seconds: int) -> str:
    named = {60: "a minute", 3600: "an hour", 86400: "a day"}

    if seconds in named:
        return named[seconds]

    if seconds % 3600 == 0:
        return f"{seconds // 3600} hours"

    if seconds % 60 == 0:
        return f"{seconds // 60} minutes"

    return f"{seconds} seconds"


def relationships(a: dict) -> list:
    return a["relationship"] if isinstance(a["relationship"], (list, tuple)) else [a["relationship"]]


def gerund(a: dict) -> str:
    kind, target, value = a["action"], a.get("target", ""), a.get("value")

    if kind == "SET_CONCURRENT_TASKS":
        return f"setting the concurrent tasks on {target} to {value}"

    if kind == "SET_RUN_SCHEDULE":
        return f"setting the run schedule of {target} to {value}"

    if kind == "SET_PROCESSOR_PROPERTY":
        return f"setting {a['property']} on {target} to {code(value)}"

    if kind == "SET_SCHEDULED_STATE":
        return f"enabling {target}" if value == "ENABLED" else f"setting {target} to {value}"

    if kind == "SET_FLOWFILE_EXPIRATION":
        return f"removing the FlowFile expiration on `{target}`" if value == "0 sec" \
            else f"setting the FlowFile expiration on `{target}` to {value}"

    if kind == "SET_BACKPRESSURE":
        limits = [f"{a['object_threshold']:,} objects"] if a.get("object_threshold") is not None else []
        limits += [a["size_threshold"]] if a.get("size_threshold") is not None else []

        return f"setting the back pressure on `{target}` to {' and '.join(limits)}"

    if kind == "ROUTE_RELATIONSHIP_TO_DLQ":
        return f"routing {join(relationships(a))} from {target} to {a['dlq']}"

    if kind == "UPDATE_PARAMETER":
        return f"changing the parameter `{a['parameter']}` to {code(value)}"

    if kind == "SCALE_DEPLOYMENT":
        return f"scaling the deployment to {a['cluster_size']} with {plural(a['nodes'], 'node')}"

    if kind == "SET_RETRY_POLICY":
        ceiling = f" with a maximum backoff of {a['max_backoff']}" if a.get("max_backoff") else ""

        return f"switching the retry backoff on {target} to {a['backoff']}{ceiling}"

    if kind == "NO_ACTION":
        return "leaving the flow alone"

    rest = ", ".join(f"{k.replace('_', ' ')} {v}" for k, v in a.items() if k not in ("action", "target"))

    return f"{kind} on {target} ({rest})" if target else f"{kind} ({rest})"


def condition(k) -> str:
    if k.kind == "system":
        return f"node CPU is {'above' if k.above is not None else 'below'} {number(k.above or k.below)}%"

    if k.kind == "connection" and k.metric == "queued_count" and k.above is not None:
        return f"the queue `{k.component}` holds more than {number(k.above)} FlowFiles"

    if k.kind == "connection" and k.metric == "percent_full" and k.above is not None:
        return f"`{k.component}` is more than {number(k.above)}% full"

    if k.kind == "processor" and k.metric in ("flowfiles_in", "flowfiles_out"):
        verb = "takes in" if k.metric == "flowfiles_in" else "sends out"

        if k.below is not None and k.below < 0.01:
            return f"{k.component} {'takes in nothing' if k.metric == 'flowfiles_in' else 'sends nothing out'}"

        bound = f"fewer than {number(k.below)}" if k.below is not None else f"more than {number(k.above)}"

        return f"{k.component} {verb} {bound} FlowFiles a second"

    bound = f"above {number(k.above)}" if k.above is not None else f"below {number(k.below)}"

    return f"{charted(k)} is {bound}"


def charted(k) -> str:
    if k.kind == "system":
        return "node CPU"

    return {
        "queued_count": f"the size of the queue `{k.component}`",
        "percent_full": f"how full `{k.component}` is",
        "queued_bytes": f"the bytes queued on `{k.component}`",
        "flowfiles_in": f"FlowFiles into {k.component}",
        "flowfiles_out": f"FlowFiles out of {k.component}",
    }.get(k.metric, f"{k.metric.replace('_', ' ')} on {k.component}")


def families(s) -> list:
    out = []

    for a in s.faults or s.expected:
        family = FAMILY.get(a["action"], "a flow edit")

        if a["action"] != "NO_ACTION" and family not in out:
            out.append(family)

    return out


def meta(s) -> str:
    if s.kind == "control":
        return f"*{KIND[s.kind]}. We watch it for {words(s.detect_within)} and expect no alert.*"

    return (f"*{KIND[s.kind]}, fixed with {join(families(s))}. We expect it to be detected within "
            f"{words(s.detect_within)} and its KPIs to be healthy within {words(s.clear_within)} of the last fix.*")


def grading(s) -> str:
    alerts = [k for k in s.kpis if k.alert and (k.above is not None or k.below is not None)]
    charts = [k for k in s.kpis if k not in alerts]
    when = " or when ".join(f"{condition(k)} for {words(k.tolerance_seconds)}" for k in alerts)
    out = []

    if not alerts:
        out.append("No KPI alerts on this one, so the problem has to be spotted in the charts.")
    elif s.kind == "control":
        out.append(f"Nothing should fire. The alert would go off if {when}.")
    else:
        out.append(f"The alert fires when {when}.")

    if charts:
        out.append(f"We {'also ' if alerts else ''}chart {join(charted(k) for k in charts)}.")

    primary = [charted(k) for k in s.kpis if k.primary]

    if primary and s.kind != "control":
        out.append(f"Whether a fix worked is decided by {join(primary)}.")

    expected = [gerund(a) for a in s.expected]
    together = ", all in one proposal" if len(expected) > 1 else ""
    accepted = f" We also accept {join((gerund(a) for a in s.acceptable), 'or')}." if s.acceptable else ""

    if s.kind == "control":
        out.append("The right answer is to leave it alone, and any change counts as a false positive.")
    elif s.faults:
        count = "both" if len(s.faults) == 2 else f"all {len(s.faults)}"
        out.append(f"Its KPIs only clear once {count} fixes are in, {join(gerund(a) for a in s.faults)}.")
        out.append(f"For the first proposal we grade {join(expected)} as the design fix{together}.{accepted}")
    else:
        out.append(f"The fix we grade as correct is {join(expected)}{together}.{accepted}")

    return " ".join(out)


def label(text: str) -> str:
    return str(text).replace("#", "#35;").replace('"', "#quot;")


def schedule(p: dict) -> str:
    period, tasks = p["schedulingPeriod"], p["concurrentlySchedulableTaskCount"]

    if p["schedulingStrategy"] == "CRON_DRIVEN":
        return f"cron {period}"

    if period == "0 sec":
        return "" if tasks == 1 else f"{tasks} tasks, 0 sec schedule"

    return f"{plural(tasks, 'task')} every {period}"


def summary(p: dict) -> tuple:
    """The settings worth reading on a diagram, and the property names they cover."""

    kind, props = p["type"].rsplit(".", 1)[-1], p["properties"]
    get = props.get

    if kind == "GenerateFlowFile":
        return [f"{get('Batch Size', '1')} × {get('File Size', '0 B')} per run"], {"Batch Size", "File Size"}

    if kind == "DebugFlow":
        return ([f"{get('FlowFile Success Iterations', '1')} succeed, then {get('FlowFile Failure Iterations', '0')} "
                 f"fail"], {"FlowFile Success Iterations", "FlowFile Failure Iterations"})

    if kind == "ControlRate":
        return [f"at most {get('Maximum Rate')} per {get('Time Duration')}"], {"Maximum Rate", "Time Duration"}

    if kind == "MergeContent":
        age = get("Max Bin Age")

        return ([f"{get('Minimum Number of Entries')} to {get('Maximum Number of Entries')} entries",
                 f"max bin age {age}" if age else "no max bin age"],
                {"Minimum Number of Entries", "Maximum Number of Entries", "Max Bin Age"})

    if kind == "CompressContent":
        return [f"{get('Compression Format')} level {get('Compression Level')}"], {"Compression Level"}

    if kind == "DuplicateFlowFile":
        return [f"{get('Number of Copies')} copies"], {"Number of Copies"}

    if kind == "InvokeHTTP":
        return [get("HTTP URL"), f"connect timeout {get('Connection Timeout')}"], {"HTTP URL", "Connection Timeout"}

    if kind == "ListenHTTP":
        return [f"port {get('Listening Port')}"], {"Listening Port"}

    if kind == "DistributeLoad":
        return [f"{get('Number of Relationships')} lanes, {get('Distribution Strategy')}"], {"Number of Relationships"}

    if kind == "SplitText":
        return [f"{plural(int(get('Line Split Count', '1')), 'line')} per split"], {"Line Split Count"}

    if kind == "EvaluateJsonPath":
        paths = {k: v for k, v in props.items() if k not in ("Destination", "Return Type")}

        return [f"{k}: {v}" for k, v in paths.items()], set(paths)

    return [], set()


def diagram(s, group) -> list:
    procs = list(group.processors.values())
    ids = {p["name"]: f"p{i}" for i, p in enumerate(procs)}
    fixes = list(s.faults or s.expected)
    named = fixes + list(s.acceptable)
    fix_procs, fix_links, dropped = set(), set(), []

    for a in fixes:
        kind, target = a["action"], a.get("target", "")

        if kind in ("SET_BACKPRESSURE", "SET_FLOWFILE_EXPIRATION"):
            fix_links.update(i for i, c in enumerate(group.connections) if c["name"] == target)
        elif kind == "UPDATE_PARAMETER":
            ref = f"#{{{a['parameter']}}}"
            fix_procs.update(p["name"] for p in procs if any(ref in str(v) for v in p["properties"].values()))
        elif kind == "ROUTE_RELATIONSHIP_TO_DLQ":
            fix_procs.add(target)
            routed = set(relationships(a))
            fix_links.update(i for i, c in enumerate(group.connections) if c["source"]["name"] == target
                             and routed & set(c["selectedRelationships"]))
            source = next((p for p in procs if p["name"] == target), None)

            if source:
                dropped += [(target, r) for r in source["autoTerminatedRelationships"] if r in routed]
        elif kind not in ("SCALE_DEPLOYMENT", "NO_ACTION") and target:
            fix_procs.add(target)

    out = ["```mermaid", f"flowchart {'LR' if len(procs) <= 6 else 'TD'}"]

    for p in procs:
        lines, covered = summary(p)
        lines += [f"{name}: {p['properties'][name]}" for name in sorted({
            a["property"] for a in named if a["action"] == "SET_PROCESSOR_PROPERTY" and a["target"] == p["name"]
        }) if name not in covered and name in p["properties"]]
        lines += [f"{name}: {value}" for name, value in p["properties"].items()
                  if name not in covered and str(value).startswith("#{")]

        if p["retriedRelationships"]:
            lines.append(f"retries {', '.join(p['retriedRelationships'])} with {p['backoffMechanism']}, "
                         f"up to {p['maxBackoffPeriod']}")

        if p["scheduledState"] == "DISABLED":
            lines.append("DISABLED")

        head = [f"<b>{p['name']}</b>", p["type"].rsplit(".", 1)[-1], schedule(p)]
        text = "<br/>".join(label(line) for line in head + lines if line)
        out.append(f'    {ids[p["name"]]}["{text}"]')

    for name, relationship in dropped:
        out.append(f'    {ids[name]}_{relationship.lower().replace(" ", "_")}(["dropped"])')

    for c in group.connections:
        source, destination = ids[c["source"]["name"]], ids[c["destination"]["name"]]
        objects, size = c["backPressureObjectThreshold"], c["backPressureDataSizeThreshold"]
        lines = [c["name"]]
        lines += [", ".join(f"relationship {r}" if r.isdigit() else r for r in c["selectedRelationships"])] \
            if c["selectedRelationships"] != ["success"] else []
        lines += [f"limit {objects:,}"] if objects != DEFAULT_CONNECTION["objects"] else []
        lines += [f"limit {size}"] if size != DEFAULT_CONNECTION["size"] else []
        lines += [f"expires after {c['flowFileExpiration']}"] \
            if c["flowFileExpiration"] != DEFAULT_CONNECTION["expiration"] else []
        lines += [c["loadBalanceStrategy"].lower().replace("_", " ")] \
            if c["loadBalanceStrategy"] != DEFAULT_CONNECTION["lb"] else []
        out.append(f'    {source} -->|"{"<br/>".join(label(line) for line in lines)}"| {destination}')

    for i, (name, relationship) in enumerate(dropped):
        fix_links.add(len(group.connections) + i)
        out.append(f'    {ids[name]} -.->|"{label(relationship)}"| {ids[name]}_{relationship.lower().replace(" ", "_")}')

    out += [f"    {style}" for style in STYLES]
    off = [ids[p["name"]] for p in procs if p["scheduledState"] == "DISABLED" and p["name"] not in fix_procs]
    fixed = [ids[name] for name in ids if name in fix_procs]
    gone = [f"{ids[name]}_{relationship.lower().replace(' ', '_')}" for name, relationship in dropped]

    for nodes, cls in ((off, "off"), (fixed, "fix"), (gone, "gone")):
        if nodes:
            out.append(f"    class {','.join(nodes)} {cls}")

    if fix_links:
        out.append(f"    linkStyle {','.join(str(i) for i in sorted(fix_links))} {FIX_LINK}")

    return out + ["```"]


def settings(p: dict) -> str:
    lines = []

    for key, value in p["properties"].items():
        if key == "Store State":
            continue

        if key == "generate-ff-custom-text":
            count = value.count("\n") + 1
            key, value = "Custom Text", f"{count} lines" if count > 1 else value

        lines.append(f"{cell(key)}: {code(value)}")

    if p["retriedRelationships"]:
        lines.append(f"**retry {', '.join(p['retriedRelationships'])} ×{p['retryCount']}, {p['backoffMechanism']}, "
                     f"max {p['maxBackoffPeriod']}**")

    if p["yieldDuration"] != "1 sec":
        lines.append(f"**yield {p['yieldDuration']}**")

    if p["executionNode"] != "ALL":
        lines.append(f"**runs on the {p['executionNode'].lower()} node**")

    return "<br>".join(lines)


def processors(group) -> list:
    out = ["| Processor | Type | Schedule | Tasks | State | Auto-terminated | Settings |",
           "|---|---|---|---|---|---|---|"]

    for p in group.processors.values():
        schedule = f"**cron `{p['schedulingPeriod']}`**" if p["schedulingStrategy"] == "CRON_DRIVEN" \
            else p["schedulingPeriod"]
        state = "**DISABLED**" if p["scheduledState"] == "DISABLED" else "enabled"
        auto = ", ".join(p["autoTerminatedRelationships"])
        out.append(f"| {cell(p['name'])} | {p['type'].rsplit('.', 1)[-1]} | {schedule} | "
                   f"{p['concurrentlySchedulableTaskCount']} | {state} | {auto} | {settings(p)} |")

    return out


def connections(group) -> list:
    out = ["| Connection | From | To | Relationships | Back pressure | Notes |", "|---|---|---|---|---|---|"]

    for c in group.connections:
        source, destination = c["source"]["name"], c["destination"]["name"]
        objects, size = c["backPressureObjectThreshold"], c["backPressureDataSizeThreshold"]
        limit = f"{objects:,}" if objects == DEFAULT_CONNECTION["objects"] else f"**{objects:,}**"
        limit += f" / {size}" if size == DEFAULT_CONNECTION["size"] else f" / **{size}**"
        flags = ["**self-loop**"] if source == destination else []

        if c["flowFileExpiration"] != DEFAULT_CONNECTION["expiration"]:
            flags.append(f"**expires after {c['flowFileExpiration']}**")

        if c["loadBalanceStrategy"] != DEFAULT_CONNECTION["lb"]:
            flags.append(f"**{c['loadBalanceStrategy'].lower().replace('_', ' ')}**")

        to = "itself" if source == destination else cell(destination)
        out.append(f"| {cell(c['name'])} | {cell(source)} | {to} | {', '.join(c['selectedRelationships'])} | "
                   f"{limit} | {', '.join(flags)} |")

    return out


def paragraphs(text: str) -> list:
    return [" ".join(paragraph.split()) for paragraph in re.split(r"\n\s*\n", text.strip())]


def scenario(s) -> list:
    group = ProcessGroup(s.id, s.group_name)
    s.build(group)
    out = [f"### {s.id} {s.title}", "", meta(s), ""]

    for paragraph in paragraphs(WALKTHROUGHS[s.id]):
        out += [paragraph, ""]

    out += diagram(s, group) + ["", f"**How it's graded.** {grading(s)}", "",
                                "<details>",
                                f"<summary>Settings: {plural(len(group.processors), 'processor')}, "
                                f"{plural(len(group.connections), 'connection')}</summary>", ""]

    if s.parameters:
        out += ["Parameters as deployed: " + ", ".join(f"`{k}` = `{v}`" for k, v in s.parameters.items()) + ".", ""]

    out += processors(group) + [""] + connections(group) + [""]

    if s.wrong:
        out += ["The tests also apply these wrong fixes and check that they don't clear the fault:", ""]
        out += [f"- {gerund(a)[0].upper()}{gerund(a)[1:]}." for a in s.wrong] + [""]

    return out + ["</details>", ""]


def render() -> str:
    intro = INTRO.format(pack_count=len(packs.PACKS), scenario_count=len(packs.SCENARIOS))
    out = [intro, "## Packs", "", "| Pack | Deployment | Size | Scenarios |", "|---|---|---|---|"]

    for pack in packs.PACKS.values():
        size = f"{pack.cluster_size} × {pack.nodes}"
        listed = ", ".join(f"[{s.id} {s.title}](#{anchor(s)})" for s in pack.scenarios)
        out.append(f"| {pack.name} | `{packs.flow_name(pack.name)}` | {size} | {listed} |")

    out.append("")

    for pack in packs.PACKS.values():
        context = f", with the parameter context `{pack.parameter_context}`" if pack.parameter_context else ""
        out += [f"## {pack.name}: {pack.title}", "",
                f"Deployed as `{packs.flow_name(pack.name)}` on {pack.cluster_size} × {pack.nodes}{context}, "
                f"in rollout wave {pack.wave}.", ""]
        out += [paragraph + "\n" for paragraph in paragraphs(PACKS[pack.name])]

        for s in pack.scenarios:
            out += scenario(s)

    return "\n".join(out).rstrip() + "\n"


def anchor(s) -> str:
    text = f"{s.id} {s.title}".lower()

    return "".join(ch for ch in text if ch.isalnum() or ch in " -").replace(" ", "-")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.strip().split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="fail if flows/scenarios/README.md is stale")
    args = parser.parse_args()
    text = render()

    if args.check:
        current = open(OUT).read() if os.path.exists(OUT) else None

        if current != text:
            print(f"{OUT} is stale; run python flows/scenario_docs.py")

            return 1

        return 0

    with open(OUT, "w") as handle:
        handle.write(text)

    print(f"wrote {OUT}")

    return 0


if __name__ == "__main__":
    sys.exit(main())
