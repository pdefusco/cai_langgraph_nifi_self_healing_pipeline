import argparse
import inspect
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from flows import packs  # noqa: E402
from flows.builder.lib import ProcessGroup  # noqa: E402

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "scenarios", "README.md")

KIND = {"classic": "Classic", "cascade": "Cascade", "compound": "Compound", "intermittent": "Intermittent",
        "slow_burn": "Slow burn", "control": "Control"}
FAMILY = {"FLOW_EDIT": "flow edit", "PARAMETER": "parameter", "SIZING": "sizing", "NONE": "no fault"}
DEFAULT_CONNECTION = {"objects": 10000, "size": "1 GB", "expiration": "0 sec", "lb": "DO_NOT_LOAD_BALANCE"}

INTRO = """\
# Test scenarios

<!-- Generated by `python flows/scenario_docs.py` from flows/scenarios/*.py. Edit those, not this file. -->

How each test scenario for the self-healing agent is built: the flow and its settings, the fault planted in it and
the arithmetic behind it, the KPIs that raise the alert, the fix graded as correct, and the plausible wrong moves it
is designed to tempt. Nothing on this page is shown to the agent.

## How the scenarios are built

- **One pack, one deployment; one scenario, one process group.** A pack is a NiFi flow definition whose root holds
  one child process group per scenario (`S22 Order Merge Deadlock`, …). Each pack is one CDF DataFlow deployment,
  `nfh-<pack>`, on NiFi 2.6.0, EXTRA_SMALL × 1 unless the pack is about sizing. Incidents, edits and grading are all
  per process group.
- **Standard processors only.** GenerateFlowFile, UpdateAttribute, LogAttribute, DebugFlow, InvokeHTTP, ListenHTTP,
  EvaluateJsonPath, MergeContent, DuplicateFlowFile, CompressContent, CryptographicHashContent, DistributeLoad,
  ControlRate, SplitText and ReplaceText. There are no external systems: a *stage* is an UpdateAttribute
  pass-through, and a *sink* is one with `success` auto-terminated.
- **The fault is in the flow as deployed.** Each group is built broken: a slow run schedule, a disabled processor, a
  self-loop, a short expiration, a low threshold, a wrong parameter. Nothing breaks it at runtime. To re-plant a
  fixed scenario, the chaos injector restores only that group from the baseline definition as a new flow version,
  resets its parameters, or resizes the deployment back.
- **Failures without real systems:**
  - DebugFlow cycles deterministically, N successes then M failures.
  - InvokeHTTP calls `10.255.255.1` (unroutable, so connects hang to the timeout) or `localhost:9999` (nothing
    listens, so calls are refused at once).
  - S17's partner is a ListenHTTP on the same node.
  - Dead-letter queues are LogAttribute at WARN. One that nothing is routed to yet is left DISABLED, because an
    enabled processor that requires input is invalid without an incoming connection.
- **Load on a clock.** Bursts, nightly batches and daily cycles use CRON_DRIVEN GenerateFlowFile with Quartz
  expressions, evaluated in UTC. `* 0-19 */2 * * ?` fires every second for minutes 0–19 of every second hour.
- **KPIs** are CDF DataFlow KPIs on the deployment.
  - An *alerts* KPI fires when its condition holds for its tolerance (default 60 s).
  - A *chart only* KPI is read by the app's detectors, for example to compare FlowFiles in against out for silent
    loss.
  - *Decides* marks the KPIs that judge whether a fix worked.
  - Every group also charts its entry processors' FlowFiles Out and its exits' FlowFiles In.
- **Grading.**
  - The *design fix* is what a scenario is built around, and *also accepted* fixes clear it too.
  - *Graded wrong* moves are applied by the tests to check that they do not clear the fault, and the *traps*
    explain why they are tempting.
  - A compound scenario lists every fix it needs before its KPIs clear.
- **Builder defaults.**
  - Every connection: back pressure 10,000 objects / 1 GB, no expiration, no load balancing.
  - Every processor: run duration 0 ms, penalty 30 sec, yield 1 sec, bulletins at WARN, all nodes.
  - The flow tables flag departures from these in **bold**.

**The rate rule.** A timer-driven processor runs each of its concurrent tasks once per run schedule, and these stages
handle one FlowFile per run, so its ceiling is **concurrent tasks ÷ run schedule**: one task every 100 ms is 10/s,
four tasks every 1 sec is 4/s, and `0 sec` is as fast as the node allows. A fault is a stage whose ceiling sits below
what arrives.

## Assumptions about NiFi behaviour

The scenarios depend on these. Where live NiFi differs, a scenario's numbers or its fix change.

1. **One FlowFile per task per trigger.** UpdateAttribute, LogAttribute and DebugFlow take one FlowFile per onTrigger
   at run duration 0 ms, so tasks ÷ schedule is their ceiling (most scenarios).
2. **Binned FlowFiles count toward back pressure** (S22). MergeContent's bins stay in the input connection's count,
   so a Minimum Number of Entries of 20,000 behind a 10,000 threshold is never reached, and the bin leaves only at
   Max Bin Age.
3. **ControlRate's limit is per node, and it runs serially** (S23, S32), so more concurrent tasks pass no more.
4. **DistributeLoad round robin skips a back-pressured relationship** (S28), so a stopped lane strands what was
   already sent to it while the other lanes take the rest.
5. **An unroutable IP hangs; localhost:9999 refuses** (S10, S17, S26). If the cluster network rejects `10.255.255.1`
   quickly instead, S10 and S17 behave like S26.
6. **Retrying with YIELD_PROCESSOR yields the whole processor** (S12), so 30% failures stall the 70% that would
   succeed; PENALIZE_FLOWFILE only delays the failing FlowFiles.
7. **Expiration drops silently** (S13, S25): an expired FlowFile leaves an EXPIRE provenance event and no bulletin.
8. **CPU calibration** (S20, S29, S34, S39, S45).
   - gzip on GenerateFlowFile's random bytes is taken as about 8 MB/s per core at level 9, 25 at level 6 and 60 at
     level 1.
   - EXTRA_SMALL is taken as 2 cores, SMALL as 3 and MEDIUM as 6.
   - These are estimates, to check against live CPU charts.
9. **A parameter fix does not fork the flow** (S17, S18, S32, S33). It updates the deployment's parameter context
   without a new flow version; editing the property in the flow would replace its `#{…}` reference.
"""


def cell(text) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def code(text) -> str:
    text = cell(text)

    return f"`{text}`" if "`" not in text else text


def plural(n: int, noun: str) -> str:
    return f"{n} {noun}" if n == 1 else f"{n} {noun}s"


def dur(seconds: int) -> str:
    if seconds % 3600 == 0:
        return f"{seconds // 3600} h"

    if seconds % 60 == 0:
        return f"{seconds // 60} min"

    return f"{seconds} s"


def action(a: dict) -> str:
    kind, target, value = a["action"], a.get("target", ""), a.get("value")
    rest = ", ".join(f"{k.replace('_', ' ')} {v}" for k, v in a.items() if k not in ("action", "target"))

    if kind == "NO_ACTION":
        return "No action: the flow is healthy"

    if kind == "SET_CONCURRENT_TASKS":
        return f"Concurrent tasks on **{target}** → **{value}**"

    if kind == "SET_RUN_SCHEDULE":
        return f"Run schedule of **{target}** → **{value}**"

    if kind == "SET_PROCESSOR_PROPERTY":
        return f"**{target}**: {a['property']} → **{cell(value)}**"

    if kind == "SET_SCHEDULED_STATE":
        return f"**{target}** → **{value}**"

    if kind == "SET_FLOWFILE_EXPIRATION":
        return f"FlowFile expiration on **{target}** → **{value}**"

    if kind == "SET_BACKPRESSURE":
        limits = [f"{a['object_threshold']:,} objects"] if a.get("object_threshold") is not None else []
        limits += [a["size_threshold"]] if a.get("size_threshold") is not None else []

        return f"Back pressure on **{target}** → **{' / '.join(limits)}**"

    if kind == "ROUTE_RELATIONSHIP_TO_DLQ":
        relationships = a["relationship"] if isinstance(a["relationship"], (list, tuple)) else [a["relationship"]]

        return f"Route **{target}** {', '.join(relationships)} → **{a['dlq']}**"

    if kind == "UPDATE_PARAMETER":
        return f"Parameter **{a['parameter']}** → **{cell(value)}**"

    if kind == "SCALE_DEPLOYMENT":
        return f"Scale the deployment to **{a['cluster_size']} × {a['nodes']}**"

    return f"{kind} on **{target}**: {cell(rest)}" if target else f"{kind}: {cell(rest)}"


def kpi(k) -> str:
    what = "node CPU %" if k.kind == "system" else f"{k.component} · {k.metric}"
    condition = f" > {k.above:,g}" if k.above is not None else f" < {k.below:,g}" if k.below is not None else ""
    tolerance = f" for {dur(k.tolerance_seconds)}" if condition and k.alert else ""
    tags = ["alerts" if k.alert else "chart only"] + (["decides"] if k.primary else [])

    return f"- `{what}{condition}{tolerance}` ({', '.join(tags)})"


def notes(build) -> str:
    out = []

    for line in inspect.getsource(build).splitlines()[1:]:
        text = line.strip()

        if not text.startswith("#"):
            break

        out.append(text.lstrip("#").strip())

    return " ".join(out)


def settings(p: dict) -> str:
    lines = []

    for key, value in p["properties"].items():
        if key == "Store State":
            continue

        if key == "generate-ff-custom-text":
            count = value.count("\n") + 1
            key, value = "Custom Text", f"{count} lines" if count > 1 else value

        lines.append(f"{cell(key)}: {code(value)}")

    if p["retriedRelationships"]:
        lines.append(f"**retry {', '.join(p['retriedRelationships'])} ×{p['retryCount']}, {p['backoffMechanism']}, "
                     f"max {p['maxBackoffPeriod']}**")

    if p["yieldDuration"] != "1 sec":
        lines.append(f"**yield {p['yieldDuration']}**")

    if p["executionNode"] != "ALL":
        lines.append(f"**runs on the {p['executionNode'].lower()} node**")

    return "<br>".join(lines) or "—"


def processors(group) -> list:
    out = ["| Processor | Type | Schedule | Tasks | State | Auto-terminated | Settings |",
           "|---|---|---|---|---|---|---|"]

    for p in group.processors.values():
        schedule = f"**cron `{p['schedulingPeriod']}`**" if p["schedulingStrategy"] == "CRON_DRIVEN" \
            else p["schedulingPeriod"]
        state = "**DISABLED**" if p["scheduledState"] == "DISABLED" else "enabled"
        auto = ", ".join(p["autoTerminatedRelationships"]) or "—"
        out.append(f"| {cell(p['name'])} | {p['type'].rsplit('.', 1)[-1]} | {schedule} | "
                   f"{p['concurrentlySchedulableTaskCount']} | {state} | {auto} | {settings(p)} |")

    return out


def connections(group) -> list:
    out = ["| Connection | From → to | Relationships | Back pressure | Notes |", "|---|---|---|---|---|"]

    for c in group.connections:
        source, destination = c["source"]["name"], c["destination"]["name"]
        objects, size = c["backPressureObjectThreshold"], c["backPressureDataSizeThreshold"]
        limit = f"{objects:,}" if objects == DEFAULT_CONNECTION["objects"] else f"**{objects:,}**"
        limit += f" / {size}" if size == DEFAULT_CONNECTION["size"] else f" / **{size}**"
        flags = ["**self-loop**"] if source == destination else []

        if c["flowFileExpiration"] != DEFAULT_CONNECTION["expiration"]:
            flags.append(f"**expires after {c['flowFileExpiration']}**")

        if c["loadBalanceStrategy"] != DEFAULT_CONNECTION["lb"]:
            flags.append(f"**{c['loadBalanceStrategy'].lower().replace('_', ' ')}**")

        to = "itself" if source == destination else cell(destination)
        out.append(f"| {cell(c['name'])} | {cell(source)} → {to} | {', '.join(c['selectedRelationships'])} | "
                   f"{limit} | {', '.join(flags) or '—'} |")

    return out


def scenario(s) -> list:
    group = ProcessGroup(s.id, s.group_name)
    s.build(group)
    timing = (f"watched {dur(s.detect_within)} for a false alarm" if s.kind == "control" else
              f"should alert within {dur(s.detect_within)}, clear within {dur(s.clear_within)} of the last fix")
    out = [f"### {s.id} {s.title}", "",
           f"*{KIND[s.kind]} · {FAMILY[s.family]} · {s.symptom.replace('_', ' ')} · {timing}*", "",
           f"**{'What is going on (no fault)' if s.kind == 'control' else 'Planted fault'}.** {s.fault}", ""]
    arithmetic = notes(s.build)

    if arithmetic:
        out += [f"> {arithmetic}", ""]

    if s.parameters:
        out += ["**Parameters as deployed:** " + ", ".join(f"`{k} = {v}`" for k, v in s.parameters.items()), ""]

    out += ["**KPIs**", ""] + [kpi(k) for k in s.kpis] + [""]

    if s.faults:
        out += [f"**Needs all {len(s.faults)} fixes to clear**", ""] + [f"- {action(a)}" for a in s.faults] + [""]
        out += ["**Graded as the right first fix**", ""]

    else:
        out += [f"**{'Expected outcome' if s.kind == 'control' else 'Design fix'}**", ""]

    out += [f"- {action(a)}" for a in s.expected] + [""]

    for title, items in (("Also accepted", [action(a) for a in s.acceptable]), ("Traps", list(s.traps)),
                         ("Graded wrong", [action(a) for a in s.wrong])):
        if items:
            out += [f"**{title}**", ""] + [f"- {item}" for item in items] + [""]

    out += ["<details>",
            f"<summary>Flow: {plural(len(group.processors), 'processor')}, "
            f"{plural(len(group.connections), 'connection')}</summary>",
            ""] + processors(group) + [""] + connections(group) + ["", "</details>", ""]

    return out


def render() -> str:
    out = [INTRO, "## Packs", "", "| Pack | Deployment | Size | Scenarios |", "|---|---|---|---|"]

    for pack in packs.PACKS.values():
        size = f"{pack.cluster_size} × {pack.nodes}"
        listed = " · ".join(f"[{s.id} {s.title}](#{anchor(s)})" for s in pack.scenarios)
        out.append(f"| {pack.name} | `{packs.flow_name(pack.name)}` | {size} | {listed} |")

    out.append("")

    for pack in packs.PACKS.values():
        doc = inspect.getmodule(pack.scenarios[0].build).__doc__.strip().split("\n\n")[1:]
        details = [f"Deployment `{packs.flow_name(pack.name)}`, {pack.cluster_size} × {pack.nodes}"]
        details += [f"parameter context `{pack.parameter_context}`"] if pack.parameter_context else []
        details += [f"rollout wave {pack.wave}"]
        out += [f"## {pack.name}: {pack.title}", "", ", ".join(details) + ".", ""]
        out += [" ".join(paragraph.split()) + "\n" for paragraph in doc]

        for s in pack.scenarios:
            out += scenario(s)

    return "\n".join(out).rstrip() + "\n"


def anchor(s) -> str:
    text = f"{s.id} {s.title}".lower()

    return "".join(ch for ch in text if ch.isalnum() or ch in " -").replace(" ", "-")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.strip().split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="fail if flows/scenarios/README.md is stale")
    args = parser.parse_args()
    text = render()

    if args.check:
        current = open(OUT).read() if os.path.exists(OUT) else None

        if current != text:
            print(f"{OUT} is stale; run python flows/scenario_docs.py")

            return 1

        return 0

    with open(OUT, "w") as handle:
        handle.write(text)

    print(f"wrote {OUT}")

    return 0


if __name__ == "__main__":
    sys.exit(main())
